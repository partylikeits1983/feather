import { test, expect } from '@playwright/test';

test('personal notes can be created, saved, searched, renamed and deleted without a workspace', async ({ page }) => {
  await page.goto('/');
  const source = page.getByRole('textbox', { name: 'Markdown source' });
  const notes = page.getByRole('tree', { name: 'Notes', exact: true });
  await expect(notes.getByRole('treeitem', { name: 'M Scratchpad.md' })).toBeVisible();
  await page.getByRole('button', { name: 'New note', exact: true }).click();
  await page.getByLabel('Note name').fill('Ideas');
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(page.locator('.document-title strong')).toHaveText('Ideas.md');
  await source.fill('# An idea to keep');
  await expect(page.getByRole('img', { name: 'Unsaved changes' })).toBeVisible();
  await page.keyboard.press('ControlOrMeta+s');
  await expect(page.getByText('Saved', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /Find a file/ }).click();
  await page.getByRole('textbox', { name: 'Find a file', exact: true }).fill('ideas');
  await page.getByRole('option', { name: 'Ideas.md Scratchpad', exact: true }).click();
  await expect(source).toContainText('An idea to keep');
  await source.fill('# Keep this edit through a rename');
  await notes.getByRole('treeitem', { name: 'M Ideas.md' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Rename', exact: true }).click();
  await page.getByLabel('Note name').fill('Journal');
  await page.getByRole('button', { name: 'Rename', exact: true }).click();
  await expect(page.locator('.document-title strong')).toHaveText('Journal.md');
  await expect(page).toHaveTitle('Journal.md — Feather');
  await expect(source).toContainText('Keep this edit through a rename');
  await page.keyboard.press('ControlOrMeta+s');
  await page.reload();
  await notes.getByRole('treeitem', { name: 'M Journal.md' }).click();
  await expect(source).toContainText('Keep this edit through a rename');
  await notes.getByRole('treeitem', { name: 'M Journal.md' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Delete note', exact: true }).click();
  await page.getByRole('button', { name: 'Keep it' }).click();
  await expect(source).toContainText('Keep this edit through a rename');
  await notes.getByRole('treeitem', { name: 'M Journal.md' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Delete note', exact: true }).click();
  await page.getByRole('button', { name: 'Delete note', exact: true }).click();
  await expect(page.locator('.document-title strong')).toHaveText('Scratchpad.md');
  await page.reload();
  await expect(notes.getByRole('treeitem')).toHaveCount(1);
});

test('note navigation protects unsaved text and failed saves', async ({ page }) => {
  await page.goto('/');
  const source = page.getByRole('textbox', { name: 'Markdown source' });
  await expect(source).toBeVisible();
  await page.keyboard.press('ControlOrMeta+n');
  await page.getByLabel('Note name').fill('Draft');
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await source.fill('# Unsaved draft');
  await page.getByRole('treeitem', { name: 'M Scratchpad.md' }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(source).toContainText('Unsaved draft');
  await page.evaluate(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function(key, value) { if (key === 'feather.notes') throw new Error('Storage full'); original.call(this, key, value); };
    Object.assign(window, { restoreNoteStorage: () => { Storage.prototype.setItem = original; } });
  });
  await page.getByRole('treeitem', { name: 'M Scratchpad.md' }).click();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Storage full');
  await expect(source).toContainText('Unsaved draft');
  await page.evaluate(() => (window as unknown as { restoreNoteStorage: () => void }).restoreNoteStorage());
  await page.getByRole('treeitem', { name: 'M Scratchpad.md' }).click();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('treeitem', { name: 'M Draft.md' }).click();
  await expect(source).toContainText('Unsaved draft');
  await source.fill('Discard this');
  await page.getByRole('treeitem', { name: 'M Scratchpad.md' }).click();
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click();
  await page.getByRole('treeitem', { name: 'M Draft.md' }).click();
  await expect(source).toContainText('Unsaved draft');
});

test('notes remain usable in a narrow sidebar with many notes', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('feather.notes', JSON.stringify(Array.from({ length: 60 }, (_, i) => ({ name: `Note ${i}.md`, contents: '' })))));
  await page.setViewportSize({ width: 1000, height: 600 });
  await page.emulateMedia({ colorScheme: 'dark' }); await page.goto('/');
  await expect(page.getByRole('button', { name: 'New note', exact: true })).toBeInViewport();
  await expect(page.getByRole('button', { name: 'Open a folder', exact: true })).toBeInViewport();
  await page.getByRole('treeitem', { name: 'M Note 59.md', exact: true }).click();
  await expect(page.locator('.document-title strong')).toHaveText('Note 59.md');
  await page.getByRole('button', { name: 'Scratchpad', exact: true }).click();
  await expect(page.getByRole('tree', { name: 'Notes', exact: true })).toBeHidden();
  await expect(page.locator('.document-title strong')).toHaveText('Note 59.md');
  await page.screenshot({ path: 'artifacts/feather-notes-collapsed.png' });
});
